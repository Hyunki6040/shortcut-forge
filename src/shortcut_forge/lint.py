"""Static checks for .shortcut plists, distilled from real on-device failures.

Each rule has an id (SFxxx), a severity and the symptom you would see on the
iPhone. Run it on anything — files built by this library, exported from the
Shortcuts app (unsigned), or generated by another tool.
"""
from __future__ import annotations

import plistlib
from dataclasses import asdict, dataclass

from .health import MICRO_UNITS

TEXT_OPS = {4, 5, 8, 9, 99, 999}
NUMBER_OPS = {0, 1, 2, 3}
SPECIAL_VARS = {"Repeat Item", "Repeat Index", "Shortcut Input", "Current Date", "Clipboard"}
LISTY_SOURCES = ("filter.", "getitemfromlist")
TEXT_UNSAFE_SOURCES = ("getvalueforkey", "choosefromlist", "filter.", "detect.dictionary", "getstoredcontent",
                       "health.quantity.get", "getitemfromlist")

RULES = {
    "SF000": ("error", "Unbalanced control flow (If/Menu/Repeat start-end mismatch)", "Shortcut fails to import or behaves randomly"),
    "SF001": ("error", "Set Stored Content input is not a text token", "Imports fine, saves nothing (later reads are empty)"),
    "SF002": ("warning", "Delete Stored Content without checking the key exists", "Error 16 when the key is missing"),
    "SF003": ("error", "Health sample logged with a micro-gram unit", "Health app reads 'mcg' as grams: 77.4 mcg becomes 77,400,000 mcg"),
    "SF004": ("error", "Health sample magnitude is a token string", "'Choose a value for each parameter' at run time"),
    "SF005": ("warning", "Text comparison on a dictionary value / chosen item without converting to text", "If shows an empty comparison field and errors"),
    "SF006": ("warning", "Dictionary key path with dots", "'Cannot evaluate key path' whenever a parent key is missing"),
    "SF007": ("warning", "Setting a property on a whole list of items", "An item picker pops up mid-run (headless runs stall)"),
    "SF008": ("error", "Health sample type is a variable", "Action rejects the parameter; the type must be fixed"),
    "SF009": ("error", "Reference to an action output that does not exist", "'Choose a value for each parameter'"),
    "SF010": ("warning", "Variable read but never set", "Empty value at run time"),
    "SF011": ("error", "Menu items and menu branches differ", "Menu shows items that do nothing, or import fails"),
    "SF012": ("error", "Number comparison without a number value", "If condition is incomplete"),
    "SF014": ("warning", "Get Contents of URL on every run without a daily cache", "Offline or a server hiccup aborts the whole shortcut (no try/catch in Shortcuts)"),
    "SF013": ("info", "Uses an iOS 26/27-only action", "Will not run on older iOS (and 'Use Model' needs Apple Intelligence)"),
}

NEW_ACTIONS = {"getstoredcontent": "iOS 27 Stored Content", "setstoredcontent": "iOS 27 Stored Content",
               "deletestoredcontent": "iOS 27 Stored Content", "askllm": "iOS 26 Use Model"}


@dataclass
class Finding:
    rule: str
    severity: str
    index: int
    action: str
    message: str
    symptom: str

    def __str__(self) -> str:  # pragma: no cover
        return f"[{self.severity.upper()}] {self.rule} #{self.index} {self.action}: {self.message} — {self.symptom}"


def _short(ident: str) -> str:
    return ident.replace("is.workflow.actions.", "")


def _refs(obj, acc: list[dict]) -> list[dict]:
    if isinstance(obj, dict):
        if obj.get("Type") in ("ActionOutput", "Variable") and ("OutputUUID" in obj or "VariableName" in obj):
            acc.append(obj)
        for v in obj.values():
            _refs(v, acc)
    elif isinstance(obj, list):
        for v in obj:
            _refs(v, acc)
    return acc


def _input_ref(p: dict) -> dict | None:
    v = p.get("WFInput")
    if isinstance(v, dict):
        if v.get("Type") == "Variable" and isinstance(v.get("Variable"), dict):
            v = v["Variable"]
        if v.get("WFSerializationType") == "WFTextTokenAttachment":
            return v.get("Value")
        if v.get("WFSerializationType") == "WFTextTokenString":
            atts = v["Value"].get("attachmentsByRange", {})
            if len(atts) == 1 and v["Value"].get("string") == "￼":
                return next(iter(atts.values()))
    return None


def lint_plist(plist: dict) -> list[Finding]:
    acts = plist.get("WFWorkflowActions", [])
    out: list[Finding] = []
    by_uuid: dict[str, tuple[int, str, dict]] = {}
    set_vars: set[str] = set()
    for i, a in enumerate(acts):
        p = a.get("WFWorkflowActionParameters", {})
        ident = _short(a.get("WFWorkflowActionIdentifier", ""))
        if p.get("UUID"):
            by_uuid[p["UUID"]] = (i, ident, p)
        if ident in ("setvariable", "appendvariable"):
            set_vars.add(p.get("WFVariableName", ""))

    def add(rule: str, i: int, ident: str, msg: str) -> None:
        sev, title, symptom = RULES[rule]
        out.append(Finding(rule, sev, i, ident, f"{title}. {msg}".strip(), symptom))

    stack: list[dict] = []
    menus: dict[str, dict] = {}
    seen_new: set[str] = set()
    for i, a in enumerate(acts):
        p = a.get("WFWorkflowActionParameters", {})
        ident = _short(a.get("WFWorkflowActionIdentifier", ""))
        mode = p.get("WFControlFlowMode")
        gid = p.get("GroupingIdentifier")

        if ident in NEW_ACTIONS and ident not in seen_new:
            seen_new.add(ident)
            add("SF013", i, ident, NEW_ACTIONS[ident])

        # --- control flow
        if gid is not None and mode is not None:
            if mode == 0:
                stack.append({"gid": gid, "ident": ident, "params": p, "index": i})
                if ident == "choosefrommenu":
                    menus[gid] = {"items": list(p.get("WFMenuItems", [])), "cases": [], "index": i}
            elif mode == 1:
                if not stack or stack[-1]["gid"] != gid:
                    add("SF000", i, ident, "middle marker outside its block")
                if ident == "choosefrommenu" and gid in menus:
                    menus[gid]["cases"].append(p.get("WFMenuItemTitle"))
            elif mode == 2:
                if not stack or stack[-1]["gid"] != gid:
                    add("SF000", i, ident, "end marker does not close the innermost block")
                else:
                    stack.pop()

        # --- references
        for r in _refs(p, []):
            if r.get("Type") == "ActionOutput" and r.get("OutputUUID") not in by_uuid:
                add("SF009", i, ident, f"output {r.get('OutputName')!r} of missing action {r.get('OutputUUID', '')[:8]}")
            if r.get("Type") == "Variable":
                name = r.get("VariableName", "")
                if name and name not in set_vars and name not in SPECIAL_VARS:
                    add("SF010", i, ident, f"variable {name!r}")

        # --- storage
        if ident == "setstoredcontent":
            st = (p.get("WFInput") or {}).get("WFSerializationType")
            if st != "WFTextTokenString":
                add("SF001", i, ident, f"key {p.get('WFStoredContentKey')!r} uses {st}")
        if ident == "deletestoredcontent":
            key = p.get("WFStoredContentKey")
            guarded = False
            for blk in stack:
                if blk["ident"] == "conditional" and blk["params"].get("WFCondition") == 100:
                    src = _input_ref(blk["params"])
                    if src and src.get("OutputUUID") in by_uuid:
                        _, sid, sp = by_uuid[src["OutputUUID"]]
                        if sid == "getstoredcontent" and sp.get("WFStoredContentKey") == key:
                            guarded = True
            prev = acts[i - 1].get("WFWorkflowActionParameters", {}) if i else {}
            if _short(acts[i - 1].get("WFWorkflowActionIdentifier", "")) == "setstoredcontent" and \
                    prev.get("WFStoredContentKey") == key:
                guarded = True  # wipe pattern: overwrite then delete
            if not guarded:
                add("SF002", i, ident, f"key {key!r}")

        # --- health
        if ident == "health.quantity.log":
            t = p.get("WFQuantitySampleType")
            if not isinstance(t, str):
                add("SF008", i, ident, "")
            q = (p.get("WFQuantitySampleQuantity") or {}).get("Value", {})
            unit = str(q.get("Unit", ""))
            if unit.strip() in MICRO_UNITS:
                add("SF003", i, ident, f"type {t!r} unit {unit!r}; log value/1000 as 'mg'")
            mag = q.get("Magnitude")
            if isinstance(mag, dict) and "WFSerializationType" in mag:
                add("SF004", i, ident, f"type {t!r}; pass the raw variable dict")

        # --- conditionals
        if ident == "conditional" and mode == 0:
            c = p.get("WFCondition")
            if c in TEXT_OPS:
                src = _input_ref(p)
                if src and src.get("OutputUUID") in by_uuid:
                    sid = by_uuid[src["OutputUUID"]][1]
                    if sid.startswith(TEXT_UNSAFE_SOURCES):
                        add("SF005", i, ident, f"left side comes from {sid}; add a Text action first")
            if c in NUMBER_OPS and "WFNumberValue" not in p:
                add("SF012", i, ident, "")

        # --- dictionaries
        if ident == "getvalueforkey":
            k = p.get("WFDictionaryKey")
            s = k["Value"]["string"] if isinstance(k, dict) and "Value" in k else k
            if isinstance(s, str) and "." in s.replace("￼", "") and not s.replace(".", "").replace(" ", "").isdigit():
                add("SF006", i, ident, f"key {s!r}; fetch one level per action")

        # --- network on the hot path
        if ident == "downloadurl" and not any(b["ident"] == "conditional" for b in stack):
            add("SF014", i, ident, "wrap it in an If that runs once a day, and cache the result")

        # --- setters on lists
        if ident.startswith("setters."):
            src = _input_ref(p)
            if src and src.get("OutputUUID") in by_uuid and by_uuid[src["OutputUUID"]][1].startswith(LISTY_SOURCES):
                add("SF007", i, ident, "wrap it in Repeat with Each and guard with Count > 0")

    for blk in stack:
        add("SF000", blk["index"], blk["ident"], "block never closed")
    for gid, m in menus.items():
        if sorted(m["items"]) != sorted(c for c in m["cases"] if c is not None):
            add("SF011", m["index"], "choosefrommenu", f"items={m['items']} cases={m['cases']}")
    order = {"error": 0, "warning": 1, "info": 2}
    out.sort(key=lambda f: (order[f.severity], f.index))
    return out


def lint_file(path: str) -> list[Finding]:
    with open(path, "rb") as f:
        head = f.read(4)
        f.seek(0)
        if head == b"AEA1":
            raise ValueError("This file is signed (AEA1 container). Lint the unsigned plist, "
                             "or export it unsigned from the Shortcuts app first.")
        return lint_plist(plistlib.load(f))


def summarize(findings: list[Finding]) -> dict:
    return {
        "errors": sum(f.severity == "error" for f in findings),
        "warnings": sum(f.severity == "warning" for f in findings),
        "info": sum(f.severity == "info" for f in findings),
        "findings": [asdict(f) for f in findings],
    }
